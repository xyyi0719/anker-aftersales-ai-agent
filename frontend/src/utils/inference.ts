/**
 * 「理解为」里关键信息的提取工具。
 *
 * 注意（B2 边界）：情绪、意图、产品一律只渲染服务/模型给的值，
 * 前端不得再从这里推断。本文件只保留「从用户原话里截取已命中的短语」这一个纯提取动作。
 */

// 只做子串匹配：命中就原样返回用户说过的那段话，不做任何推断或补充。
const KEY_INFO_KW = [
  '充不进电', '充不进去', '充不上电', '无法充电', '充电慢',
  '没声音', '单边无声', '一边没声音', '连不上', '配对失败',
  '鼓包', '冒烟', '起火', '漏液', '黑屏', '不吸',
  '退货', '退款', '换货', '保修', '质保', '召回',
];

export function extractKeyInfo(query: string): string | undefined {
  return KEY_INFO_KW.find(k => query.includes(k));
}
